#!/usr/bin/env node
/**
 * Assemble the published stylesheet.
 *
 * ## Why this exists instead of letting tsup copy CSS
 *
 * tsup's `copy` loader renames a component stylesheet to a content-hashed file
 * (`widget-BHSVXUOB.css`) and drops it at the output root. That is fine for
 * applications, where the bundler resolves the import, but it makes the file
 * unreachable from the single published stylesheet: a consumer who imports
 * `uireload/styles.css` would silently get tokens and base styles with none of the
 * component rules, and the component would render unstyled.
 *
 * Silently shipping unstyled components is not an acceptable failure mode, so the
 * stylesheet is assembled here instead.
 *
 * ## Output
 *
 * One self-contained `dist/index.css`:
 *
 *   1. `@layer` order declaration. Must come first, or later layers win over it.
 *   2. `src/theme/tokens.css`
 *   3. `src/index.css` (base and utilities)
 *   4. Every `src/components/<name>/*.css`, in sorted order
 *
 * No `@import` survives into the output: the bundle owns ordering, so the published
 * file has no runtime resolution step and no ordering dependency on how the consumer
 * imports it.
 *
 * Component CSS must wrap its rules in `@layer uireload.components`. This script
 * verifies that rather than silently emitting unlayered rules, which would jump the
 * layer stack and beat the declared order.
 */

import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "src");
const DIST = join(ROOT, "dist");

/**
 * Explicit, not alphabetical. Tokens must precede every rule that consumes them so a
 * consumer overriding a token later in the file still wins on source order alone.
 */
const LAYERS = "uireload.tokens, uireload.base, uireload.utilities, uireload.components";

const COMPONENT_LAYER = "@layer uireload.components";

/** Component stylesheets, in a stable order. Private `_` folders are excluded. */
function componentStylesheets() {
  const dir = join(SRC, "components");
  if (!existsSync(dir)) return [];

  const files = [];

  for (const entry of readdirSync(dir, { withFileTypes: true }).sort((a, b) =>
    a.name < b.name ? -1 : 1
  )) {
    if (!entry.isDirectory() || entry.name.startsWith("_")) continue;

    for (const file of readdirSync(join(dir, entry.name)).sort()) {
      if (file.endsWith(".css")) files.push(join(dir, entry.name, file));
    }
  }

  return files;
}

/** Remove `@import` statements; the bundle resolves ordering itself. */
function stripImports(css) {
  return css.replace(/^\s*@import[^;]+;\s*$/gm, "");
}

/** True when the stylesheet wraps its rules in the component layer. */
function declaresComponentLayer(css) {
  return css.includes(COMPONENT_LAYER);
}

function banner(files) {
  return [
    "/*",
    " * uireload stylesheet. Generated by scripts/bundle-css.mjs -- do not edit.",
    " *",
    " * Import once, near the root of your application:",
    " *",
    ' *   import "uireload/styles.css";',
    " *",
    " * Source files:",
    ...files.map((file) => ` *   - ${relative(ROOT, file).replace(/\\/g, "/")}`),
    " */",
    "",
  ].join("\n");
}

function main() {
  const componentCss = componentStylesheets();

  const problems = componentCss.filter(
    (file) => !declaresComponentLayer(readFileSync(file, "utf8"))
  );
  if (problems.length > 0) {
    console.error(
      "\nEvery component stylesheet must wrap its rules in `@layer uireload.components`.\n" +
        "Unlayered rules jump the declared layer order and would beat consumer overrides.\n\n"
    );
    for (const file of problems) {
      console.error(`  ${relative(ROOT, file).replace(/\\/g, "/")}`);
    }
    console.error("");
    process.exit(1);
  }

  const sources = [
    join(SRC, "theme", "tokens.css"),
    join(SRC, "index.css"),
    ...componentCss,
  ].filter(existsSync);

  const sections = [
    `@layer ${LAYERS};`,
    ...sources.map((file) => {
      const css = stripImports(readFileSync(file, "utf8")).trim();
      return `/* ---- ${relative(ROOT, file).replace(/\\/g, "/")} ---- */\n${css}`;
    }),
  ];

  const output = `${banner(sources)}\n${sections.join("\n\n")}\n`;

  mkdirSync(DIST, { recursive: true });
  writeFileSync(join(DIST, "index.css"), output, "utf8");

  const kib = (Buffer.byteLength(output) / 1024).toFixed(2);
  console.log(
    `Bundled dist/index.css from ${sources.length} source file(s) ` +
      `(${componentCss.length} component) -> ${kib} kB`
  );
}

main();
